把符合动作方向的平淡动词换成有狼狈感的动词：冲过去可以滑铲，缓慢挪动可以蠕动，突然抬头可以弹射，失控争辩可以咆哮。动作夸张到能让人看见，但说明借力、障碍和落点，让下一步事故有东西可接。

