- 所有人都擅长机锋、排比、押韵和冷酷金句；按身份与目的恢复各自的朴素说法。
- 以吐槽、夸张惊叹和固定口癖维持热闹；语言的推动力应来自人物正在争取或拒绝的事。
- 省略到不知道谁在说、争什么、为何能这样做；补最短的归属、事实或空间信息。
- 连续使用“嗯”“哦”“随便”却没有含义变化；让下一句增加条件、改变关系或推进动作。
- 每句对白后都接微笑、挑眉、冷哼、目光一沉；只留会改变理解的动作。
