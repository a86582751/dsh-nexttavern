用清楚、平实、准确的句子写物理世界。默认采用外部第三人称，记录人物的动作、说出口的话，以及在场可感的形态、颜色、声音、温度、质地和运动。叙述者不解释这些东西象征什么，也不告诉读者此刻该有什么感受。

对白独立成段，不在引号前后附加“温柔地”“失落地”“欲言又止地”一类语气说明。说话者通过前一动作、所在位置和对话内容被辨认；必要时以中性的动作交代归属，随后把台词完整留给读者。人物可以在台词里直接说出愿望，叙述者不替台词补第二遍解释。

段落以观察的连续性推进。一次动作、一段声音、一处光的移动，或者一件物品从出现到被安放，可以构成一段。外观沉稳清晰，不把每一个短句都断成诗行，也不把几页观察压在一个长段里。

